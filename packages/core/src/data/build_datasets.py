#!/usr/bin/env python3
"""Build the embedded canonical causal-inference datasets (-> sibling *.ts files).

Reproducible: fetches each public dataset, extracts a dense numeric matrix + role metadata,
and writes a `CovariateDataset` TypeScript module. Run from the repo root:

    python3 packages/core/src/data/build_datasets.py

Requires: pandas, numpy (and network access). Datasets:
  - nhefs    : Hernan & Robins NHEFS public-use (causaldata).            covariates only.
  - ihdp     : Infant Health & Development Program, npci sim (Hill 2011). true ITE (mu0/mu1).
  - twins    : US same-sex twins <2kg (Louizos 2017 / CEVAE).            both potential outcomes.
  - lalonde  : National Supported Work job-training trial (causaldata).  RCT + earnings outcome.
"""
import io, json, sys, urllib.request
import numpy as np, pandas as pd

HERE = __file__.rsplit("/", 1)[0]


def fetch(url: str) -> bytes:
    return urllib.request.urlopen(url, timeout=60).read()


def emit(name: str, source: str, df: pd.DataFrame, covariates, treatment=None, outcome=None,
         potential_outcomes=None, true_ate=None, experimental_flag=None, const=None):
    cols = list(df.columns)
    rows = df.to_numpy(dtype=float)
    rows_js = ",".join(
        "[" + ",".join((str(int(v)) if float(v).is_integer() else str(round(float(v), 4))) for v in row) + "]"
        for row in rows)
    meta = {"name": name, "source": source, "covariates": list(covariates)}
    if treatment: meta["treatment"] = treatment
    if outcome: meta["outcome"] = outcome
    if potential_outcomes: meta["potentialOutcomes"] = list(potential_outcomes)
    if true_ate is not None: meta["trueAte"] = round(float(true_ate), 4)
    if experimental_flag: meta["experimentalFlag"] = experimental_flag
    fields = "".join(f"  {k}: {json.dumps(v)},\n" for k, v in meta.items())
    ts = (f'import type {{ CovariateDataset }} from "./dataset";\n\n'
          f'// {source}. {len(rows)} rows, {len(cols)} columns. Auto-generated by build_datasets.py.\n'
          f'export const {const}: CovariateDataset = {{\n{fields}'
          f'  columns: {json.dumps(cols)},\n  rows: [{rows_js}]\n}};\n')
    path = f"{HERE}/{name}.ts"
    open(path, "w").write(ts)
    import os
    print(f"  wrote {name}.ts  {os.path.getsize(path)//1024} KB  {len(rows)}x{len(cols)}"
          + (f"  trueATE={true_ate:.2f}" if true_ate is not None else ""))


def build_nhefs():
    raw = fetch("https://raw.githubusercontent.com/NickCH-K/causaldata/main/Python/causaldata/nhefs/nhefs.dta")
    df = pd.read_stata(io.BytesIO(raw))
    cols = ["sex", "age", "race", "education", "smokeintensity", "smokeyrs", "active", "exercise", "wt71"]
    sub = df[cols].apply(lambda s: pd.to_numeric(s.astype("string"), errors="coerce")).dropna()
    emit("nhefs", "NHEFS public-use (Hernan & Robins, via causaldata)", sub, covariates=cols, const="NHEFS_COVARIATES")


def build_ihdp():
    txt = fetch("https://raw.githubusercontent.com/AMLab-Amsterdam/CEVAE/master/datasets/IHDP/csv/ihdp_npci_1.csv").decode()
    df = pd.read_csv(io.StringIO(txt), header=None)
    names = ["treatment", "y_factual", "y_cfactual", "mu0", "mu1"] + [f"x{i}" for i in range(1, df.shape[1] - 4)]
    df.columns = names
    covs = [c for c in names if c.startswith("x")]
    keep = covs + ["treatment", "y_factual", "mu0", "mu1"]
    emit("ihdp", "IHDP npci-1 (Hill 2011, via CEVAE) — real covariates, simulated outcome", df[keep],
         covariates=covs, treatment="treatment", outcome="y_factual",
         potential_outcomes=("mu0", "mu1"), true_ate=(df["mu1"] - df["mu0"]).mean(), const="IHDP_DATASET")


def build_twins():
    base = "https://raw.githubusercontent.com/AMLab-Amsterdam/CEVAE/master/datasets/TWINS/"
    X = pd.read_csv(io.StringIO(fetch(base + "twin_pairs_X_3years_samesex.csv").decode()))
    T = pd.read_csv(io.StringIO(fetch(base + "twin_pairs_T_3years_samesex.csv").decode()))
    Y = pd.read_csv(io.StringIO(fetch(base + "twin_pairs_Y_3years_samesex.csv").decode()))
    covs = ["gestat10", "dmar", "mpcb", "cigar6", "drink5", "wtgain", "mager8", "meduc6", "mrace", "frace", "birattnd", "pldel"]
    covs = [c for c in covs if c in X.columns]
    df = pd.DataFrame({c: pd.to_numeric(X[c], errors="coerce") for c in covs})
    df["w_lighter"], df["w_heavier"] = T["dbirwt_0"], T["dbirwt_1"]
    df["y0"], df["y1"] = pd.to_numeric(Y["mort_0"], errors="coerce"), pd.to_numeric(Y["mort_1"], errors="coerce")
    df = df[(df.w_lighter < 2000) & (df.w_heavier < 2000)].dropna()
    df = df.sample(n=min(2500, len(df)), random_state=11).reset_index(drop=True)
    df["birthweight_gap"] = (df.w_heavier - df.w_lighter)
    out = df[covs + ["birthweight_gap", "y0", "y1"]]
    emit("twins", "US same-sex twins <2kg (Louizos 2017 / CEVAE) — both potential outcomes", out,
         covariates=covs + ["birthweight_gap"], outcome="y1", potential_outcomes=("y0", "y1"),
         true_ate=(df.y1 - df.y0).mean(), const="TWINS_DATASET")


def build_lalonde():
    raw = fetch("https://raw.githubusercontent.com/NickCH-K/causaldata/main/Python/causaldata/nsw_mixtape/nsw_mixtape.dta")
    df = pd.read_stata(io.BytesIO(raw))
    covs = [c for c in ["age", "educ", "black", "hisp", "marr", "nodegree", "re74", "re75"] if c in df.columns]
    keep = covs + ["treat", "re78"]
    sub = df[keep].apply(pd.to_numeric, errors="coerce").dropna()
    emit("lalonde", "National Supported Work (LaLonde 1986 / Mixtape, via causaldata) — RCT job training", sub,
         covariates=covs, treatment="treat", outcome="re78", const="LALONDE_DATASET")


def build_synthetic():
    # "Generative" stand-in: a Gaussian copula LEARNED from the real NHEFS rows -> novel synthetic
    # rows (rank->normal, fit correlation, resample, invert via empirical quantiles).
    from scipy.stats import norm
    rng = np.random.default_rng(7)
    raw = fetch("https://raw.githubusercontent.com/NickCH-K/causaldata/main/Python/causaldata/nhefs/nhefs.dta")
    df = pd.read_stata(io.BytesIO(raw))
    cols = ["sex", "age", "race", "education", "smokeintensity", "smokeyrs", "active", "exercise", "wt71"]
    X = df[cols].apply(lambda s: pd.to_numeric(s.astype("string"), errors="coerce")).dropna().to_numpy(float)
    n, d = X.shape
    Z = norm.ppf((np.argsort(np.argsort(X, axis=0), axis=0) + 0.5) / n)
    L = np.linalg.cholesky(np.corrcoef(Z, rowvar=False) + 1e-6 * np.eye(d))
    m = 2000
    U = norm.cdf((L @ rng.standard_normal((d, m))).T)
    Xnew = np.column_stack([np.sort(X[:, j])[np.clip((U[:, j] * n).astype(int), 0, n - 1)] for j in range(d)])
    emit("nhefs-synthetic", "Synthetic NHEFS from a learned Gaussian copula (generative stand-in)",
         pd.DataFrame(Xnew, columns=cols), covariates=cols, const="NHEFS_SYNTHETIC")


if __name__ == "__main__":
    builders = {"nhefs": build_nhefs, "ihdp": build_ihdp, "twins": build_twins, "lalonde": build_lalonde,
                "nhefs-synthetic": build_synthetic}
    targets = sys.argv[1:] or list(builders)
    for t in targets:
        print(f"building {t} ...")
        try:
            builders[t]()
        except Exception as e:  # noqa
            print(f"  FAILED {t}: {e}")
